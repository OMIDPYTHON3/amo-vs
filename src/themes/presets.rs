pub const BUILTIN_NAMES: [&str; 9] = [
    "Dark+ (default dark)",
    "Light+ (default light)",
    "Dracula",
    "Nord",
    "Tokyo Night",
    "Catppuccin Mocha",
    "Monokai",
    "GitHub Dark",
    "One Dark Pro",
];

pub fn builtin(name: &str) -> Option<Theme> {
    if name.eq_ignore_ascii_case(BUILTIN_NAMES[0]) { return Some(dark_plus::dark_plus()); }
    if name.eq_ignore_ascii_case(BUILTIN_NAMES[1]) { return Some(dark_plus::light_plus()); }
    if name.eq_ignore_ascii_case(BUILTIN_NAMES[2]) { return Some(dracula()); }
    if name.eq_ignore_ascii_case(BUILTIN_NAMES[3]) { return Some(nord()); }
    if name.eq_ignore_ascii_case(BUILTIN_NAMES[4]) { return Some(tokyo_night()); }
    if name.eq_ignore_ascii_case(BUILTIN_NAMES[5]) { return Some(catppuccin_mocha()); }
    if name.eq_ignore_ascii_case(BUILTIN_NAMES[6]) { return Some(monokai()); }
    if name.eq_ignore_ascii_case(BUILTIN_NAMES[7]) { return Some(github_dark()); }
    if name.eq_ignore_ascii_case(BUILTIN_NAMES[8]) { return Some(one_dark_pro()); }
    None
}

pub fn all() -> Vec<Theme> { BUILTIN_NAMES.iter().filter_map(|n| builtin(n)).collect() }

pub fn slug(name: &str) -> String {
    let s = name.to_lowercase()
        .replace(" (default dark)", "")
        .replace(" (default light)", "")
        .replace(' ', "_");
    match s.as_str() {
        "dark+" => "dark_plus".to_string(),
        "light+" => "light_plus".to_string(),
        _ => s,
    }
}
