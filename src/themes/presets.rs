//! Complete built-in theme palettes. Each theme overrides every major UI
//! surface (editor, activity bar, sidebar, tabs, panel, status bar, dialogs,
//! selection/cursor and syntax roles), not just the background color.

use super::dark_plus;
use super::theme::Theme;
use ratatui::style::Color;

fn hex(s: &str) -> Color {
    let s = s.trim_start_matches('#');
    let r = u8::from_str_radix(&s[0..2], 16).unwrap_or(0);
    let g = u8::from_str_radix(&s[2..4], 16).unwrap_or(0);
    let b = u8::from_str_radix(&s[4..6], 16).unwrap_or(0);
    Color::Rgb(r, g, b)
}

